# ------------------------------------------------------------------ chart
def chart():
    W, H, L, R, T, B = 760, 380, 56, 190, 18, 46
    pw, ph = W - L - R, H - T - B
    ymax = 50.0

    def X(m):
        return L + pw * m / 9.0

    def Y(v):
        return T + ph * (1 - v / ymax)

    out = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-labelledby="ct" '
           f'class="chart"><title id="ct">Worst boundary-layer cell skew '
           f'against camber</title>']
    for v in range(0, 51, 10):
        out.append(f'<line x1="{L}" x2="{L + pw}" y1="{Y(v):.1f}" '
                   f'y2="{Y(v):.1f}" class="grid"/>'
                   f'<text x="{L - 8}" y="{Y(v) + 4:.1f}" class="tick" '
                   f'text-anchor="end">{v}°</text>')
    for m in CAMBER:
        out.append(f'<text x="{X(m):.1f}" y="{T + ph + 18}" class="tick" '
                   f'text-anchor="middle">{m}%</text>')
    out.append(f'<text x="{L + pw / 2}" y="{H - 6}" class="axis" '
               f'text-anchor="middle">maximum camber (NACA m412)</text>')
    series = [
        ("s2", "Deformed from NACA 0012", def_0, 0),
        ("s3", "Deformed from NACA 4412", def_4, 0),
        ("s1", "Regenerated by AeroMesh", reg_s, 0),
    ]
    for cls, name, data, _ in series:
        pts = " ".join(f"{X(m):.1f},{Y(d['bl_skew_max']):.1f}"
                       for m, d in zip(CAMBER, data))
        out.append(f'<polyline points="{pts}" class="line {cls}"/>')
        for m, d in zip(CAMBER, data):
            tip = (f"{name} · {m}% camber: worst skew "
                   f"{d['bl_skew_max']:.1f}°, 99th percentile "
                   f"{d['bl_skew_p99']:.1f}°")
            out.append(f'<circle cx="{X(m):.1f}" cy="{Y(d["bl_skew_max"]):.1f}"'
                       f' r="4.5" class="dot {cls}" tabindex="0" '
                       f'data-tip="{tip}"><title>{tip}</title></circle>')
        last = data[-1]["bl_skew_max"]
        out.append(f'<text x="{X(9) + 12}" y="{Y(last) + 4:.1f}" '
                   f'class="lab">{name}</text>'
                   f'<text x="{X(9) + 12}" y="{Y(last) + 19:.1f}" '
                   f'class="lab sub">{last:.1f}° at 9%</text>')
    out.append("</svg>")
    return "".join(out)


