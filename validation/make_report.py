def solver_rows():
    rows = []
    for key, (name, alpha, rad) in LABELS.items():
        c = naca["cases"].get(key)
        if c is None:
            continue
        ref = naca["reference"][str(c["alpha"])]
        clp = "–" if c["cl_pct_vs_ref"] is None else f"{c['cl_pct_vs_ref']:+.1f}%"
        yp = "–" if not c["yplus"] else f"{c['yplus'][2]:.2f} / {c['yplus'][1]:.2f}"
        state = ("" if c["finished"] else
                 f' <span class="pill run">{c["iterations"]} it, running</span>')
        rows.append(
            f"<tr><td>{name}{state}</td><td>{alpha}</td><td>{rad}</td>"
            f"<td>{c['cells']:,}</td>"
            f"<td>{c['cl']:.4f}</td><td>{ref['cl']:.4f}</td><td>{clp}</td>"
            f"<td>{c['cd']:.5f}</td><td>{ref['cd']:.5f}</td>"
            f"<td>{c['cd_counts_vs_ref']:+.1f}</td>"
            f"<td>{c['cd_drift'] * 1e4:.2f}</td><td>{yp}</td></tr>")
    return "".join(rows)


